#ifndef GAME_MAIN_H
#define GAME_MAIN_H

// 依赖库头文件（确保编译时能找到EasyX相关函数/类型）
#include <graphics.h>
#include <conio.h>

// 窗口与游戏区域配置宏（全局常量，供所有包含该头文件的文件使用）
#define WIDTH 1024          // 总窗口宽度
#define HEIGHT 768          // 总窗口高度
#define GAME_WIDTH 840      // 游戏核心区域宽度
#define GAME_HEIGHT 600     // 游戏核心区域高度
#define GAP 40              // 方格间距（部署/地图网格单位）

// 全局变量声明（extern表示"此处仅声明，定义在.cpp文件中"，避免重复定义）
extern int random_num;

// 函数声明（与.cpp文件中函数定义的返回值、参数列表完全一致）
/**
 * @brief 游戏初始化函数
 * @details 初始化EasyX窗口、绘制边框/网格、加载资源、初始化得分/难度/最高记录、生成初始预览防御单位
 */
void Game_Init();

/**
 * @brief 游戏主循环
 * @details 持续处理用户输入→更新游戏状态（敌人/防御塔/得分）→绘制游戏画面→控制帧率
 */
void Game_Loop();

/**
 * @brief 游戏退出处理
 * @details 保存最高分到文件、释放加载的资源、关闭EasyX窗口
 */
void Game_Quit();

/**
 * @brief 绘制游戏地图
 * @details 根据随机数选择3种地图之一，颜色规则：
 *          红色(RGB(196,43,28))=敌方基地 | 蓝色(RGB(36,98,255))=我方基地
 *          棕色(RGB(185,128,71))=可部署区域 | 深红色(RGB(53,17,10))=不可通行区域
 * @param random_num 地图选择参数（取值范围：1-3）
 *
 * 
 * @brief 地图1：对称布局地图
 * @details 敌方基地位于四个角落，我方基地位于中央
 *          防御单位可部署区域为左右两侧的对称矩形
 *
 * @par 地图特征：
 * - 敌方基地：四个角落的2×2方格区域
 * - 我方基地：中央(10,7)位置
 * - 可部署区域：左右两侧的对称矩形区域
 *
 * @par 防御单位可部署区域（棕色方块）：
 * 坐标范围（列，行）：
 * 1. 左侧区域：列(5-7), 行(3-11)
 *    包含3列×9行 = 27个方格
 * 2. 右侧区域：列(13-15), 行(3-11)
 *    包含3列×9行 = 27个方格
 *
 * @par 战术特点：
 * - 完全对称布局，敌人从四个方向进攻
 * - 可部署区域集中，适合建立密集防线
 * - 需要同时防御四个方向的敌人
 *
 *
 * @brief 地图2：通道式布局地图
 * @details 敌方基地位于顶部多个点，我方基地位于底部中央
 *          防御单位可部署区域为左右两侧的垂直通道和底部横向通道
 *
 * @par 地图特征：
 * - 敌方基地：顶部多个独立方格
 * - 我方基地：底部中央(10,13)位置
 * - 可部署区域：通道式布局
 *
 * @par 防御单位可部署区域（棕色方块）：
 * 坐标范围（列，行）：
 * 1. 左右两侧主通道：列(0-1), 行(4-14)
 *    各2列×11行 = 22个方格
 * 2. 左右两侧突出：列(2), 行(7-14)
 *    各1列×8行 = 8个方格
 * 3. 左右两侧进一步突出：列(3), 行(8-9)
 *    各1列×2行 = 2个方格
 * 4. 左右底部突出：列(3-6), 行(13-14)
 *    各4列×2行 = 8个方格
 * 5. 底部中央通道：列(7-13), 行(14)
 *    7列×1行 = 7个方格
 *
 * @par 区域总面积：87个方格
 *
 * @par 战术特点：
 * - 敌人从顶部多个点发起进攻
 * - 可部署区域形成垂直和水平通道
 * - 适合引导敌人通过特定路径
 * - 可在通道转弯处设置火力交叉
 *
 *
 * @brief 地图3：多层包围布局地图
 * @details 敌方基地位于四个角落的阶梯状区域，我方基地位于中央
 *          防御单位可部署区域为多层三角形和菱形布局
 *
 * @par 地图特征：
 * - 敌方基地：四个角落的阶梯状三角形区域
 * - 我方基地：正中央(10,7)位置
 * - 不可通行区域：地图边缘的深红色区域
 * - 可部署区域：多层包围布局
 *
 * @par 防御单位可部署区域（棕色方块）：
 * 坐标范围（列，行）：
 *
 * @section top_triangles 顶部和底部三角形区域
 * 1. 顶部左侧三角形：
 *    - 列(7-9), 行(0): 3个方格
 *    - 列(8-9), 行(1): 2个方格
 *    - 列(9), 行(2): 1个方格
 *    总计：6个方格
 * 2. 顶部右侧三角形：对称区域，6个方格
 * 3. 底部左侧三角形：行(12-14)对称，6个方格
 * 4. 底部右侧三角形：行(12-14)对称，6个方格
 *
 * @section center_columns 上下中央列区域
 * 5. 顶部中央列：列(10), 行(0-3): 4个方格
 * 6. 底部中央列：列(10), 行(11-14): 4个方格
 *
 * @section middle_layers 中间菱形区域
 * 7. 中间第一层：行(4), 列(4-6)和列(14-16): 6个方格
 * 8. 中间第二层：行(5), 列(5-7)和列(13-15): 6个方格
 * 9. 底部第一层：行(9), 列(4-6)和列(14-16): 6个方格
 * 10. 底部第二层：行(10), 列(5-7)和列(13-15): 6个方格
 *
 * @par 区域总面积：72个方格
 *
 * @par 战术特点：
 * - 复杂的多层次布局
 * - 敌人从四个角落阶梯式进攻
 * - 可建立纵深防御体系
 * - 适合不同类型防御单位的搭配
 *
 */
void Game_Map(int random_num);

#endif // GAME_H
